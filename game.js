let animalMoveLoop = null

function startAnimalMovement(){

  if(animalMoveLoop) clearInterval(animalMoveLoop)

  /* 🧠 INIT STATE */
  document.querySelectorAll(".animal").forEach(el=>{
    if(!el.dataset.vx){
      el.dataset.vx = (Math.random()*4 - 2)
      el.dataset.vy = (Math.random()*4 - 2)
      el.dataset.moving = "true"
      el.dataset.pauseTimer = 0
    }
  })

  animalMoveLoop = setInterval(()=>{

    document.querySelectorAll(".animal").forEach(el=>{

      if(el.dataset.caught === "true") return

      const animal = el.dataset.animal

      let left = parseFloat(el.style.left)
      let top  = parseFloat(el.style.top)

      let vx = parseFloat(el.dataset.vx)
      let vy = parseFloat(el.dataset.vy)

      let moving = el.dataset.moving === "true"
      let pauseTimer = parseInt(el.dataset.pauseTimer)

      /* ⏸️ START / STOP SYSTEM (FLOAT + DRIFT) */

      if(moving && Math.random() < 0.02){
        el.dataset.moving = "false"
        el.dataset.pauseTimer = 10 + Math.random()*20
        return
      }

      if(!moving){
        pauseTimer--
        el.dataset.pauseTimer = pauseTimer

        if(pauseTimer <= 0){
          el.dataset.moving = "true"
        }

        return
      }

      /* ===================================================== */
      /* 🐌 SNAIL — SMOOTH SLIDE */
      /* ===================================================== */

      if(animal === "🐌"){

        vx += (Math.random()*0.4 - 0.2)
        vy += (Math.random()*0.4 - 0.2)

        vx = Math.max(-1.5, Math.min(1.5, vx))
        vy = Math.max(-1.5, Math.min(1.5, vy))

        el.style.transition = "0.6s ease-in-out"

        /* 👉 flip LEFT/RIGHT */
        el.style.transform = vx < 0
          ? "scaleX(-1)"
          : "scaleX(1)"
      }

      /* ===================================================== */
      /* 🐛 WORM — PULSE CRAWL */
      /* ===================================================== */

      else if(animal === "🐛"){

        vx += (Math.random()*0.5 - 0.25)
        vy += (Math.random()*0.5 - 0.25)

        vx = Math.max(-2, Math.min(2, vx))
        vy = Math.max(-2, Math.min(2, vy))

        el.style.transition = "0.3s ease-in-out"

        /* 🐛 squish-stretch feel */
        const pulse = Math.sin(Date.now()/150) * 0.15

        el.style.transform = `
          scaleX(${vx < 0 ? -1 : 1})
          scaleY(${1 + pulse})
        `
      }

      /* ===================================================== */
      /* 🐞 BEETLE — STEP + ROTATE */
      /* ===================================================== */

      else if(animal === "🐞"){

        vx += (Math.random()*0.8 - 0.4)
        vy += (Math.random()*0.8 - 0.4)

        if(Math.random() < 0.05){
          vy -= 4   // hop
        }

        vx = Math.max(-3, Math.min(3, vx))
        vy = Math.max(-3, Math.min(3, vy))

        el.style.transition = "0.3s ease-out"

        /* 🔄 rotate to direction */
        const angle = Math.atan2(vy, vx) * (180/Math.PI)
        el.style.transform = `rotate(${angle}deg)`
      }

      /* ===================================================== */
      /* 🦋 BUTTERFLY — FLOAT + TURN */
      /* ===================================================== */

      else if(animal === "🦋"){

        vx += Math.sin(Date.now()/800) * 0.2
        vy += Math.cos(Date.now()/900) * 0.2

        vx = Math.max(-3, Math.min(3, vx))
        vy = Math.max(-3, Math.min(3, vy))

        el.style.transition = "0.5s ease-in-out"

        const angle = Math.atan2(vy, vx) * (180/Math.PI)
        el.style.transform = `rotate(${angle}deg)`
      }

      /* ===================================================== */
      /* 🐝 BEE — FAST + SHARP TURN */
      /* ===================================================== */

      else if(animal === "🐝"){

        vx += (Math.random()*1 - 0.5)
        vy += (Math.random()*1 - 0.5)

        vx = Math.max(-6, Math.min(6, vx))
        vy = Math.max(-6, Math.min(6, vy))

        el.style.transition = "0.15s linear"

        const angle = Math.atan2(vy, vx) * (180/Math.PI)
        el.style.transform = `rotate(${angle}deg)`
      }

      /* 🧠 APPLY MOVEMENT */

      left += vx
      top  += vy

      const MIN = 8
      const MAX = 92

      if(left < MIN || left > MAX){
        vx *= -1
        left = Math.max(MIN, Math.min(MAX, left))
      }

      if(top < MIN || top > MAX){
        vy *= -1
        top = Math.max(MIN, Math.min(MAX, top))
      }

      el.dataset.vx = vx
      el.dataset.vy = vy

      el.style.left = left + "%"
      el.style.top  = top + "%"

    })

  }, 120)
}


