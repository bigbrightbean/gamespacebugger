function landRoll(original, stage, big, result){

  const isWin = result === targetShape
  const team = currentTeam          // 🔒 the team that scores = the team that picked

  rollBox.classList.remove("rolling","fast","tease")
  rollBox.classList.add("landed")

  /* 🎉 the final shape pops out BIG over the caught creature */
  const pop = document.createElement("div")
  pop.className = "shape-pop " + (isWin ? "win" : "miss")
  pop.innerHTML = `<div class="shape-big">${result}</div>
                   <div class="shape-word">${isWin ? "YAY! " + shapeName(result) + "!" : "Oops! " + shapeName(result)}</div>`
  stage.appendChild(pop)

  if(isWin){

    /* 🌟 the scoring shape — the big show */
    rollBox.classList.add("rare")
    big.classList.add("gold")

    fireworksFrom(rollBox, 4)
    showRays(rollBox, 3600)
    burstFrom(rollBox, 24, [targetShape,"⭐","✨"])
    setTimeout(()=> burstFrom(pop, 26, [targetShape,"🌟","✨"]), 500)

    startConfetti()
    setTimeout(stopConfetti, 3000)

    /* ✈️ a copy of the shape flies into the team's score slot */
    setTimeout(()=> flyToSlot(pop.querySelector(".shape-big"), team, ()=> addPoint(team)), 2300)

  }else{

    fireworksFrom(rollBox, 1)

  }

  /* creature + net disappear */
  setTimeout(()=>{
    stage.classList.add("gone")
    setTimeout(()=>{
      stage.remove()
      original.remove()
    }, 500)
  }, isWin ? 3300 : 2200)

  /* ➡️ next turn (or the win!) */
  setTimeout(()=>{
    if(dogScore >= WIN_COUNT || tigerScore >= WIN_COUNT){
      resetRollBox()
      isBusy = false
      finishGame()
    }else{
      endTurn()
    }
  }, isWin ? 4400 : 2900)
}


/* ✈️ flying shape → score slot */
function flyToSlot(fromEl, team, done){

  const slot = nextSlot(team)
  const a = fromEl.getBoundingClientRect()
  const b = slot.getBoundingClientRect()

  const fly = document.createElement("div")
  fly.className = "fly-shape"
  fly.textContent = targetShape
  fly.style.left = (a.left + a.width/2) + "px"
  fly.style.top  = (a.top + a.height/2) + "px"
  document.body.appendChild(fly)

  const dx = (b.left + b.width/2) - (a.left + a.width/2)
  const dy = (b.top + b.height/2) - (a.top + a.height/2)

  fly.animate([
    { transform:"translate(-50%,-50%) scale(2.2) rotate(0deg)", opacity:1 },
    { transform:`translate(calc(-50% + ${dx*0.5}px), calc(-50% + ${dy*0.5 - 120}px)) scale(1.6) rotate(200deg)`, opacity:1, offset:0.5 },
    { transform:`translate(calc(-50% + ${dx}px), calc(-50% + ${dy}px)) scale(0.8) rotate(360deg)`, opacity:1 }
  ], { duration:800, easing:"cubic-bezier(.5,0,.4,1)", fill:"forwards" })

  /* timer (not the animation event) so the point always lands on time */
  setTimeout(()=>{ fly.remove(); done() }, 820)
}


