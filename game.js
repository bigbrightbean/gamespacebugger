function createRow(container, left, right, step){

  container.innerHTML = ""

  const wrap = document.createElement("div")
  wrap.className = "phonics-block"

  const letterRow = document.createElement("div")
  letterRow.className = "letter-row"

  /* 🔤 LETTER BOXES */

  const leftBox = document.createElement("div")
  leftBox.className = "letter-btn active"
  leftBox.innerText = left

  const rightBox = document.createElement("div")
  rightBox.className = "letter-btn active"
  rightBox.innerText = right

  leftBox.onclick = ()=>{ if(!isBoardLocked) leftBox.classList.toggle("selected") }
  rightBox.onclick = ()=>{ if(!isBoardLocked) rightBox.classList.toggle("selected") }

  letterRow.appendChild(leftBox)
  letterRow.appendChild(rightBox)

  /* 👉 SLIDER */

  const slider = document.createElement("div")
  slider.className = "slider-bar"

  const handle = document.createElement("div")
  handle.className = "car-handle"
  handle.innerText = "👉🏻"
  handle.style.transform = "scale(1.5)"

  slider.appendChild(handle)

  wrap.appendChild(letterRow)
  wrap.appendChild(slider)

  container.appendChild(wrap)


  /* 🎯 BLEND ANIMATION */

  let done = false

  handle.onclick = ()=>{

    if(done || isBoardLocked || gameOver) return

    if(!leftBox.classList.contains("selected") ||
       !rightBox.classList.contains("selected")) return

    done = true

    const leftRect = leftBox.getBoundingClientRect()
    const rightRect = rightBox.getBoundingClientRect()

    const target = rightRect.left - leftRect.left - (leftRect.width * 0.7)

    const duration = 380
    const start = performance.now()

    function animate(time){

      const progress = Math.min((time - start)/duration, 1)
      const eased = progress * progress

      leftBox.style.position = "relative"
      leftBox.style.left = (target * eased) + "px"

      handle.style.left = (slider.offsetWidth - handle.offsetWidth) * eased + "px"

      /* 💥 IMPACT + MERGE */
      if(progress >= 1){

        leftBox.style.visibility = "hidden"

        const result = leftBox.innerText + rightBox.innerText

        rightBox.innerText = result
        rightBox.classList.remove("active")
        rightBox.classList.add("blended")

        /* STEP 1 → update the next row */
        if(step === 1){
          firstBlend = result
          const nextLeft = row2.querySelector(".letter-btn")
          if(nextLeft) nextLeft.innerText = result
        }

        /* STEP 2 → word done: lock the word, open the sea */
        if(step === 2){
          isBoardLocked = true
          setTimeout(()=>{ unlockGame() }, 800)
        }

        return
      }

      requestAnimationFrame(animate)
    }

    requestAnimationFrame(animate)

  }

}


