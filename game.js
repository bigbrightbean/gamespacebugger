function loadWord(wordObj){

  if(isBoardLocked) return

  currentWord = wordObj

  /* BUILD BLEND */
  firstBlend = wordObj.parts[0] + wordObj.parts[1]

  /* LOAD IMAGE */
  loadImage(wordObj.image)

  /* BUILD ROWS */
  createRow(row1, wordObj.parts[0], wordObj.parts[1], 1)
  createRow(row2, firstBlend, wordObj.parts[2], 2)

}


