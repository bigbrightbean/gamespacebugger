function onThemeChange(){

  if(isBusy){
    themeSelector.value = currentTheme
    colorSelector.value = currentColor
    return
  }

  currentTheme = themeSelector.value
  currentColor = colorSelector.value
  applyTheme()
  fillColorOptions()

  themeSelector.blur()
  colorSelector.blur()
  newGame()
}

/* colour dropdown shows the colours in the chosen shape */
function fillColorOptions(){
  colorSelector.innerHTML = COLOR_KEYS.map(k =>
    `<option value="${k}"${k === currentColor ? " selected" : ""}>${THEME_EMOJI[currentTheme][k]} ${COLOR_NAMES[k]}</option>`
  ).join("")
}

themeSelector.onchange = onThemeChange
colorSelector.onchange = onThemeChange
fillColorOptions()


