/* moderator can switch words any time — except while the
   net + spin animation is playing. If the word was already
   blended, the sea locks again until the new word is blended. */
function moderatorSwitch(newIndex){
  if(typeof isBusy !== "undefined" && isBusy) return
  if(typeof gameOver !== "undefined" && gameOver) return

  if(isBoardLocked){
    isBoardLocked = false
    if(typeof lockField === "function") lockField()
  }

  currentIndex = (newIndex + words.length) % words.length
  loadWord(words[currentIndex])
}

shuffleBtn.onclick = ()=>{
  let n = currentIndex
  if(words.length > 1){
    while(n === currentIndex) n = Math.floor(Math.random()*words.length)
  }
  moderatorSwitch(n)
}

prevWordBtn.onclick = ()=> moderatorSwitch(currentIndex - 1)

nextWordBtn.onclick = ()=> moderatorSwitch(currentIndex + 1)

mainMenuBtn.onclick = ()=>{
  window.location.href = "index.html"
}

