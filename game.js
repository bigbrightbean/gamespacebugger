const REEL_SPINS = 26

function shapeHTML(sh){
  return `<div class="reel-digit shape c-${EMOJI_COLOR[sh]}${sh === targetShape ? " is-target" : ""}">${sh}</div>`
}

function randomShape(){
  return SHAPES[Math.floor(Math.random()*SHAPES.length)]
}

/* builds the strip and returns the index of the "near miss" shape
   (the one it pretends to stop on before sliding to the real one) */
function buildReel(finalShape){

  const list = []
  let prev = ""

  for(let i = 0; i < REEL_SPINS; i++){
    let sh
    do{ sh = randomShape() }while(sh === prev)
    list.push(sh)
    prev = sh
  }

  /* 😮 near miss — often teases the scoring shape! */
  let near
  if(finalShape !== targetShape && Math.random() < 0.5){
    near = targetShape
  }else{
    do{ near = randomShape() }while(near === finalShape)
  }

  if(list[list.length-1] === near){
    list[list.length-1] = SHAPES.find(x => x !== near && x !== finalShape && x !== list[list.length-2]) || near
  }

  list.push(near)
  list.push(finalShape)

  /* one extra below, so the bounce never shows empty space */
  let after
  do{ after = randomShape() }while(after === finalShape)
  list.push(after)

  reelStrip.innerHTML = list.map(shapeHTML).join("")

  return REEL_SPINS   // index of the near-miss shape
}

function startRoll(original, stage, big){

  const result = original.dataset.secret

  reelStrip.getAnimations().forEach(a=>a.cancel())
  rollBox.className = "roll-box rolling fast " + currentTeam

  const nearIdx = buildReel(result)
  const h = reelStrip.firstElementChild.offsetHeight
  const y = i => `translateY(${-i*h}px)`

  /* 🎵 fast fast fast → slows down → stops on one...
         → hesitates → SLIDES to the real one */
  const anim = reelStrip.animate([
    { transform:y(0),                    easing:"linear",                       offset:0     },
    { transform:y(nearIdx - 10),         easing:"cubic-bezier(.2,.6,.35,1)",    offset:0.299 },
    { transform:y(nearIdx),              easing:"ease-in-out",                  offset:0.636 },
    { transform:y(nearIdx + 0.22),       easing:"ease-in-out",                  offset:0.738 },
    { transform:y(nearIdx + 0.04),       easing:"cubic-bezier(.34,1.5,.64,1)",  offset:0.804 },
    { transform:y(nearIdx + 1),                                                 offset:1     }
  ], { duration:4600, fill:"forwards" })

  setTimeout(()=> rollBox.classList.remove("fast"), 1500)
  setTimeout(()=> rollBox.classList.add("tease"), 2900)

  anim.finished.then(()=> landRoll(original, stage, big, result))
}


